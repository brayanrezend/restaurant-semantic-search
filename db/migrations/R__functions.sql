CREATE OR REPLACE FUNCTION yelp_str(p VARCHAR2) RETURN VARCHAR2 DETERMINISTIC IS
BEGIN
  IF p IS NULL OR TRIM(p) = 'None' THEN
    RETURN NULL;
  END IF;
  RETURN LOWER(REGEXP_REPLACE(TRIM(p), '^u?''(.*)''$', '\1'));
END;
/

CREATE OR REPLACE FUNCTION yelp_bool(p VARCHAR2) RETURN BOOLEAN DETERMINISTIC IS
BEGIN
  RETURN CASE yelp_str(p) WHEN 'true' THEN TRUE WHEN 'false' THEN FALSE END;
END;
/

CREATE OR REPLACE FUNCTION yelp_dict_to_json(p VARCHAR2) RETURN VARCHAR2 DETERMINISTIC IS
BEGIN
  IF p IS NULL OR TRIM(p) = 'None' THEN
    RETURN NULL;
  END IF;
  RETURN REPLACE(REPLACE(REPLACE(REPLACE(
           REGEXP_REPLACE(p, '([{ ,])u''', '\1'''),
           '''', '"'), 'True', 'true'), 'False', 'false'), 'None', 'null');
END;
/
